const radius = 5;
const area = Math.PI * radius ** 2;
console.log(`The area of a circle with radius ${radius} is ${area.toFixed(2)}`);

const length = 10;
const width = 5;
const rectangleArea = length * width;
console.log(`The area of a rectangle with length ${length} and width ${width} is ${rectangleArea.toFixed(2)}`);

const height = 10;
const volume = area * height;
console.log(`The volume of a cylinder with radius ${radius} and height ${height} is ${volume.toFixed(2)}`);